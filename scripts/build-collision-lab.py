#!/usr/bin/env python3
"""Build a browser-only collision laboratory from the REAL authoritative game logic.

The test lab never changes rooms, player records, or the live match state.
Original OC PNG assets are referenced, never altered.
"""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
PUBLIC=ROOT/"public"
SERVER=(ROOT/"server.js").read_text(encoding="utf-8")
CLIENT=(PUBLIC/"app.js").read_text(encoding="utf-8")

def extract(source,start,end):
    left=source.find(start)
    right=source.find(end,left+len(start))
    if left<0 or right<=left:
        raise RuntimeError(f"Collision lab cannot extract {start!r} to {end!r}")
    return source[left:right].rstrip()

parts=[
    "// Auto-generated from server.js and app.js; do not edit this file.",
    "(function(){",
    "'use strict';",
    "const GAME_CONTENT=globalThis.GAME_CONTENT;",
    "if(!GAME_CONTENT?.characters)throw Error('Please load content-pack.js first.');",
    "let randomCursor=0;",
    "const rand=n=>randomCursor++%n; // Test-only: cycle ordinary quotes in order.",
    "const roleName=id=>GAME_CONTENT.characters[id]?.name||id;",
    extract(SERVER,"const COLLISION_LINES=","const startIndex ="),
    "const startIndex = [39,26,0,13];",
    "const LAUNCH=-2, TURN=49, LANE=50, GOAL=55, RING_SIZE=52;",
    extract(SERVER,"const keyOnBoard =","function projection("),
    extract(SERVER,"function projection(","// 特殊移动的停留格都应判撞"),
    extract(SERVER,"const crossedLane =","function captureAlong("),
    extract(SERVER,"function captureAlong(","function legalMove("),
    extract(CLIENT,"const COLOR=[","const ORDER="),
    extract(CLIENT,"const RING=[","const PIPS="),
    """function point(color,pos,id=0){
 if(pos===LAUNCH)return LAUNCH_POINT[color];
 if(pos===-1){const [x,y]=COLOR[color].base;return [x+PADS[id][0],y+PADS[id][1]];}
 if(pos===GOAL)return LANES[COLOR[color].key][GOAL-LANE];
 if(pos<LANE)return RING[(COLOR[color].start+pos)%52];
 return LANES[COLOR[color].key][pos-LANE];
}""",
    "globalThis.COLLISION_LAB_ENGINE=Object.freeze({projection,captureAlong,collisionLine,keyOnBoard,point,COLOR,GOAL,LANE,LAUNCH,resetQuotes:()=>{randomCursor=0;}});",
    "})();",
    "",
]
out="\n".join(parts)
destination=PUBLIC/"collision-lab-engine.js"
if not destination.exists() or destination.read_text(encoding="utf-8")!=out:
    destination.write_text(out,encoding="utf-8")
    print("updated",destination.relative_to(ROOT))
else:
    print("unchanged",destination.relative_to(ROOT))
